# "is" vs "==" in Python...




# "is"... : It compares the exact value of object in Memory.... 

# "=="... : It compares values...









# # Example 1... 


# a = 4
# b = "4"

# print(a is b)               # Exact location of Object in Memory
# print(a == b)               # Compares Value









# # Example 3... Single Value


# a = 5
# b = 5

# print(a is b)
# print( a == b)









# # Example 3... List 


# a = [1, 2, 3]
# b = [1, 2, 3]

# print(a is b)
# print( a == b)









# # Example 4... Tuple 


# a = (1, 2, 3)
# b = (1, 2, 3)

# print(a is b)
# print( a == b)














