# Types of Features of OOPs... 


# 1. Encapsulation ---> Internal state of an Object is hidden and can only be accessed or modified through the object's Method... 


# 2. Inheritance ---> It allows new classes to be created that inherit the properties and methods of an existing class. This allows for code to reuse and makes it easy to create new classes that have similar functions to existing classes... 


# 3. Polymorphism ---> The object of different classes can be treated as if they were objects of a common class. This allows for greater flexibility in code and makes it easier to write code that can work with multiple types of objects...

