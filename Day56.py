# # There are 2 main factors of OOPs... 

# 1. Class
# 2. Objects






# *** Class... : A class is a blueprint or template for creating objects. It defines the properties and methods that an object of the class will have. Properties are the data or state of an objects and methods are the actions or behaviour that an object can perform...


# *** Object... : An object is an instance of a class and it contains its own data and methods. For example You could create a class called person that has properties such as name an age and methods such as speak() and walk(). Each instance of the person class wouls be a unique object with its own naame and age, but they would all have the same methods to speak and walk...









